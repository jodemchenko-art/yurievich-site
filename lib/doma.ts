export const TERRACE_RATE = 15000;

/** Пример расчёта: площадь застройки этажей (без террасы) и терраса, м². */
export function calcHouse(k: Komplektaciya, floor1: number, floor2: number, terrace: number, bigLiving = false) {
  const r1 = bigLiving ? k.rate1Big : k.rate1;
  const r2 = bigLiving ? k.rate2Big : k.rate2;
  return floor1 * r1 + floor2 * r2 + terrace * TERRACE_RATE;
}

export function fmtMln(n: number): string {
  return (n / 1_000_000).toLocaleString('ru-RU', { minimumFractionDigits: 1, maximumFractionDigits: 2 }) + ' млн ₽';
}

