export const SECOND_FLOOR_DISCOUNT = 10000;
export const TERRACE_RATE = 15000;

/** Ориентировочная стоимость дома: этаж × ставка + этаж × (ставка − 10 000) + терраса × 15 000. */
export function estimateHouse(c: Complectation, floor1: number, floor2 = 0, terrace = 0, living = 0) {
  const base = living > 150 ? c.priceBig : c.price;
  return floor1 * base + floor2 * (base - SECOND_FLOOR_DISCOUNT) + terrace * TERRACE_RATE;
}

