export const photosBy = (group: LivePhoto['group']) => LIVE_PHOTOS.filter((p) => p.group === group);

/**
 * Совместимость: страницы /obekty/, /doma/, /otzyvy/, /o-kompanii/ работают по тегам.
 * Теги выводятся из group/stage, чтобы один массив фото кормил обе схемы.
 */
export type TaggedPhoto = LivePhoto & { tags: string[] };

const STAGE_TAGS: Record<string, string[]> = {
  'Армокаркас': ['armo'],
  'Заливка': ['zalivka'],
  'Подготовка основания': ['zemlya'],
  'Ленточный фундамент': ['lenta'],
  'Плита с рёбрами': ['rebra', 'lenta'],
  'Зимняя стройка': ['zima'],
  'Портрет': ['portret'],
  'Юрий на объекте': ['komanda'],
};
const GROUP_TAGS: Record<LivePhoto['group'], string[]> = { slab: ['plita'], house: ['doma'], team: ['komanda'] };

export const GALLERY: TaggedPhoto[] = LIVE_PHOTOS.map((p) => ({
  ...p,
  tags: Array.from(new Set([...(GROUP_TAGS[p.group] || []), ...(STAGE_TAGS[p.stage] || [])])),
}));

export const byTag = (tag: string) => GALLERY.filter((p) => p.tags.includes(tag));
